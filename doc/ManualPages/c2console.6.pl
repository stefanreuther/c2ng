section('Command Language',
        paragraph_text('A <b>command</b> consists of a number of <b>words</b> separated by spaces.',
                       'The first word is the command name, all subsequent words are parameters.',
                       'Example:'),
        paragraph_synopsis('    echo hello'),
        paragraph_text('If words contain special characters (including spaces), they can be quoted using single quotes, double quotes, or braces.',
                       'Single-quoted words end at the next single quote, and can contain no further special characters.',
                       'Double-quoted words allow quoting of special characters using a backslash.',
                       'Brace-quoted words end at the next closing brace, honoring quotes and nested braces.'),
        paragraph_synopsis('    echo "hello"',
                           "    echo 'hello'",
                           '    echo {hello {nested}}'),
        paragraph_text('Brace quoting is typically used to pass a command as parameter to another command, as in'),
        paragraph_synopsis('    if $c {',
                           '      command',
                           '    }'),
        paragraph_text('In double-quoted words, you can use <b>\0</b> (null), <b>\n</b> (newline), <b>\r</b> (carriage-return), <b>\t</b> (tab),',
                       '<b>\u</b><i>####</i> (Unicode hex-escape, produces UTF-8), and <b>\x</b><i>##</i> (hex-escape, produces single byte) escapes;',
                       'every other character after backslash produces itself (most notably, <b>\\</b> (backslash), <b>\$</b> (dollar) and <b>\"</b> (quote)).'),
        paragraph_text('In unquoted and double-quoted words, you can use <b>$</b><i>X</i> (one-character name)',
                       'or <b>${</b><i>XXX</i><b>}</b> to refer to script environment variables.',
                       'Unlike in a shell, variables are <i>not</i> further split into words.'),
        paragraph_text('If a word is preceded by a <b>&lt;</b> (less-than) sign, the file named by the word is read and its content used instead. Example:'),
        paragraph_synopsis('    echo &lt;file.txt'),
        paragraph_text('Commands can be arranged in a <b>pipeline</b> by separating them with a <b>|</b> pipe character.',
                       'This causes the result of the first command to be appended as additional parameters to the second command.',
                       'Idioms using this are:'),
        paragraph_synopsis('    # read value from redis and place in environment variable',
                           '    redis get somekey | setenv k',
                           '',
                           '    # retrieve a list and iterate through it',
                           '    talk forumlsthread 1 | foreach i {talk threadstat $i | echo}'),
        paragraph_text('Commands produce a result or a failure.',
                       'If the result is not null, it will be shown as output.'),
    );

section('Commands',
        paragraph_text('By default, the console is in <b>global context</b>.',
                       'Topic-specific commands are in additional contexts.',
                       'To execute a topic specific command, you can use <i>topic command...</i>,',
                       'or enter the topic context using <i>topic</i>, and entering the subsequent commands without <i>topic</i> prefix.',
                       'Global commands are always accepted.'),
        paragraph_synopsis('    # topic plus command',
                           '    talk forumlsthread 1',
                           '    talk forumlsthread 2',
                           '',
                           '    # topic, then commands',
                           '    talk',
                           '    forumlsthread 1',
                           '    forumlsthread 2'),
        paragraph_text('The <b>..</b> (dot-dot), <b>up</b> or <b>exit</b> command closes the active topic context.'));

