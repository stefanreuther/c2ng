subsect('Router Connection Context',
        paragraph_text('The <b>router</b> context talks to the <link>c2router-server(6)</link> service.',
                       'Commands are sent to the service as-is,',
                       'unless they match a built-in command.',
                       'As another exception, if a session has been selected and a command matches a session command,',
                       'it is submitted to that session (by prefixing it with an <b>S</b> line).'),
        paragraph_detail('<b>repeat</b> <i>N</i> <i>COMMAND...</i>',
                         paragraph_text('For benchmarking: repeat the given command and discard the result.',
                                        'Print time taken;')),
        paragraph_detail('<b>s</b> <i>N</i> <i>COMMAND...</i>',
                         paragraph_text('Submit the given command to a session;')),
        paragraph_detail('<b>s</b> <i>N</i>',
                         paragraph_text('Select session for future session commands.',
                                        'Session commands are <b>help</b>, <b>stat</b>, <b>get</b>, <b>post</b>, <b>quit</b>, and parameterless <b>save</b>.',
                                        'Note that there currently is no way to send a <b>post</b> payload.')));

subsect('Export Context',
        paragraph_text('The <b>export</b> context replaces the former <b>c2dbexport</b> utility.',
                       'Each of the commands will produce a script on standard output, that will recreate the exported situation in a way.'),
        paragraph_detail('<b>db</b> [<b>--delete</b>] <i>WILDCARD</i>...',
                         paragraph_text('Export database keys matching the given wildcards.',
                                        'The resulting script will add these keys to the target database instance.',
                                        'With <b>--delete</b>, the script will start with a command to delete all keys matching the given wildcards,',
                                        'allowing import into a nonempty database.')),
        paragraph_detail('<b>object</b> [<b>--</b><i>OPTION</i>] <i>TYPE</i><b>:</b><i>ID</i>...',
                         paragraph_text('Export objects from database, preserving links.',
                                        'The resulting script will add these objects to the target database instance.',
                                        'Links will be preserved, i.e. if the object is a user, their PMs will be exported,',
                                        'and the names of the users they were sent to.'),
                         paragraph_text('Option <b>--recursive</b> (default) requests the following objects with full details and related objects.',
                                        'Option <b>--full</b> requests the following objects with full details, but only base information for related objects.',
                                        'Option <b>--header</b> requests only the bare minimum object header ("this object exists").',
                                        'Output will be redacted to contain user-specific information only if the user is part of the export with at least full level.'),
                         paragraph_text('Option <b>--files=inline</b> (default) requests that files contained in the export job are represented as inline strings in the resulting script.',
                                        'Option <b>--files=normal</b> will create a directory <i>host</i> or <i>user</i>,',
                                        'and place files in it according to their location in the file service; the result script will read them from there.',
                                        'Option <b>--files=dedup</b> will create files under names corresponding to their content hash, storing each file copy only once.',
                                        'Especially for game exports, this will save a lot of disk space because backups are very repetetive,',
                                        'but will make it impossible to manually analyze the exported files using other tools.',
                                        'Option <b>--files=none</b> disables export of files.'),
                         paragraph_text('Supported object types are:',
                                        '<b>email</b> (email address),',
                                        '<b>file</b>/<b>userfile</b> (user file, <i>ID</i> is directory name),',
                                        '<b>forum</b> (forum, <i>ID</i> is numeric Id),',
                                        '<b>game</b> (game, <i>ID</i> is numeric Id),',
                                        '<b>group</b> (forum group, <i>ID</i> is group name),',
                                        '<b>host</b> (host version, <i>ID</i> is name),',
                                        '<b>hostfile</b> (host file, <i>ID</i> is directory name),',
                                        '<b>master</b> (master utility, <i>ID</i> is name),',
                                        '<b>msg</b>/<b>post</b> (forum post, <i>ID</i> is numeric Id),',
                                        '<b>pm</b> (private message, <i>ID</i> is numeric Id),',
                                        '<b>shiplist</b> (ship list, <i>ID</i> is name),',
                                        '<b>thread</b> (forum thread, <i>ID</i> is numeric Id),',
                                        '<b>token</b> (login token, <i>ID</i> is token value),',
                                        '<b>tool</b> (host utility, <i>ID</i> is name),',
                                        '<b>user</b> (user, <i>ID</i> is user Id).')));

